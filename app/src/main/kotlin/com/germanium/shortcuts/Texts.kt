fun Context.tr(key: String, vararg args: Any): String {
    val id = Texts.ids[key] ?: R.string.ui_err_generic
    return if (args.isEmpty()) getString(id) else getString(id, *args)
}
@Composable fun t(key: String, vararg args: Any): String {
    val id = Texts.ids[key] ?: R.string.ui_err_generic
    return if (args.isEmpty()) stringResource(id) else stringResource(id, *args)
}
fun Context.describe(error: Throwable): String = when (error) {
    is Problem -> tr(error.key, *error.arguments)
    is FutureShortcutVersion -> tr("err_future_shortcut", error.requiredVersion)
    is InvalidDocument -> tr("err_xml")
    is SecurityException -> tr("err_permission")
    is java.util.concurrent.TimeoutException -> tr("err_timeout")
    is java.io.IOException -> tr("err_io")
    else -> if (error.message in Texts.ids) tr(error.message!!) else tr("err_generic")
}
